// 按来源的主题门槛：综合类大部委只收与本台主题（AI 与数字/文化内容政策）相关的标题，其余不入库。
//
// 为什么需要：全局 __domain__ 词表里有「产业、企业、经济、项目、投资、标准、示范」等宽泛词，
// 政府标题几乎都会命中一个，门槛对多数来源形同虚设。以前没暴露，是因为工信部 / 国务院这些大来源
// 一直配错抓取方式、扫描为 0；2026-10 修好后，一次本地抓取进来 152 条，多数是升国旗、中小企业座谈、
// 电池 / 纺织规划这类与主题无关的内容。所以只给这两类综合部委加一层更严的主题词，其他来源不受影响。
// （与创作者雷达给 PetaPixel 加的门槛是同一个思路：同一个问题、同一种解法，复用到两个领域。）
// 全局词表过宽是原有问题，见 /sources 说明，后续再整体梳理。

/** 主题词：AI、数据要素、数字内容与文化政策。刻意不收「数据」「智能」这类单字词（会放进「经济数据」「智能家居」） */
const POLICY_TOPIC = new RegExp(
  [
    "人工智能",
    String.raw`(?<![A-Za-z])AI(?![A-Za-z])`,
    "大模型",
    "智能体",
    "生成式",
    "算力",
    "算法",
    "大数据",
    "数据要素",
    "数据资源",
    "数据产业",
    "数据安全",
    "公共数据",
    "数字", // 数字化、数字经济、数字园区、数字文化……
    "软件",
    "互联网",
    "平台经济",
    "信息服务",
    "网络安全",
    "元宇宙",
    "虚拟现实",
    "增强现实",
    "机器人",
    "视听",
    "广电",
    "广播电视",
    "影视",
    "电影",
    "短视频",
    "微短剧",
    "直播",
    "游戏",
    "动漫",
    "文化",
    "文旅",
    "出版",
    "传媒",
    "版权",
    "著作权",
    "创意",
  ].join("|"),
  "i",
);

/** 匹配前先去掉部门名：「工业和信息化部举行升国旗仪式」不该因为部门名里的字放行 */
const DEPARTMENT_NAMES = /工业和信息化部|工信部|国务院/g;

/** 需要主题门槛的抓取类型：工信部专用抓取、国务院栏目 JSON（2026-10 修好的两类综合部委来源） */
const GATED_TYPES = new Set(["miit_list", "govcn_json"]);

/** 该来源的条目能否入库：不在门槛范围内的来源一律放行 */
export function passesSourceTopicGate(sourceType: string | null | undefined, title: string | null | undefined): boolean {
  if (!sourceType || !GATED_TYPES.has(sourceType)) return true;
  return POLICY_TOPIC.test((title ?? "").replace(DEPARTMENT_NAMES, ""));
}
